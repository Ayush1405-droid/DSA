s = "hello world" #create a string

s.upper()          #convert the string to uppercase

s.lower()          #convert the string to lowercase

s.replace("world", "Python") #replace a substring in the string

len(s)              #get the length of the string

s = s + "!" #concatenate a string to the existing string

s = s.strip() #remove leading and trailing whitespace from the string

s = s.split() #split the string into a list of words